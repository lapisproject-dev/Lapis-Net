package net.lapisphilosophorum.lapisnet.onion

import net.lapisphilosophorum.lapisnet.onion.OnionConstants.BODY_SIZE
import net.lapisphilosophorum.lapisnet.onion.OnionConstants.LAYER_OVERHEAD
import net.lapisphilosophorum.lapisnet.onion.OnionConstants.MAX_HOPS
import java.security.SecureRandom

/*
 * Onion layering with fixed-size cells and no tagging channel.
 *
 * Let O = LAYER_OVERHEAD (16 tag + 1 type byte) and BODY = 1019. A layer for hop i (1-based) has
 * size BODY - (i-1)*O. Every layer is `seal(type | inner)`:
 *
 *  forward, client -> hop k (k <= hopCount):
 *      m (length BODY - k*O) -> layer_k = seal_Kf_k(LOCAL | m) -> layer_{i} = seal_Kf_i(FORWARD | layer_{i+1}) ...
 *      -> layer_1 has exactly BODY bytes.
 *  forward, relay i: opens the first BODY-(i-1)*O bytes. LOCAL: deliver. FORWARD: the inner layer
 *      (BODY - i*O bytes) is followed by i*O FRESH random bytes and passed on.
 *  backward, origin hop k: seal_Kb_k(ORIGIN | m) (BODY-(k-1)*O bytes) + (k-1)*O random bytes.
 *  backward, relay i < k: seal_Kb_i(WRAPPED | first BODY-i*O bytes) + (i-1)*O fresh random bytes.
 *  backward, client: opens layers 1..j until the type byte says ORIGIN.
 *
 * Anti-tagging rule: every byte that is NOT covered by the AEAD tag of the receiving hop is
 * discarded and regenerated by that hop. Unauthenticated filler that an honest hop forwarded
 * unchanged would be a covert channel by which two colluding, non-adjacent relays (guard and exit)
 * could mark a cell. With this rule every bit that is ever evaluated is authenticated per hop: a
 * flipped bit in an authenticated region fails the tag at the next honest hop (forward) or at the
 * client (backward); a flipped bit in the unauthenticated tail is simply discarded. What this does
 * NOT prevent: an adversary that deliberately causes a circuit to be destroyed and correlates the
 * teardown (see docs/anonymity.adoc).
 */

private const val TYPE_LOCAL: Byte = 0x01
private const val TYPE_FORWARD: Byte = 0x02
private const val TYPE_ORIGIN: Byte = 0x11
private const val TYPE_WRAPPED: Byte = 0x12

/** Size of the layer addressed to hop [hopIndex] (1-based): `BODY - (hopIndex-1)*O`. */
internal fun layerSize(hopIndex: Int): Int = BODY_SIZE - (hopIndex - 1) * LAYER_OVERHEAD

private fun typed(
    type: Byte,
    inner: ByteArray,
): ByteArray {
    val out = ByteArray(inner.size + 1)
    out[0] = type
    inner.copyInto(out, 1)
    return out
}

private fun padToBody(
    sealed: ByteArray,
    random: SecureRandom,
): ByteArray {
    require(sealed.size <= BODY_SIZE) { "layer larger than cell body" }
    val out = ByteArray(BODY_SIZE)
    sealed.copyInto(out)
    fillRandom(out, sealed.size, random)
    return out
}

/** Client side of an established (or being-built) circuit. Thread-safe via a monitor. Any exception
 * thrown by [wrapForward] or [unwrapBackward] leaves per-hop counters in an unspecified state: the
 * circuit must be discarded. */
class ClientCircuit internal constructor() : AutoCloseable {
    private class Hop(
        val forward: HopCipher,
        val backward: HopCipher,
    )

    private val hops = ArrayList<Hop>(MAX_HOPS)

    val hopCount: Int @Synchronized get() = hops.size

    @Synchronized
    internal fun addHop(keys: CircuitHopKeys) {
        check(hops.size < MAX_HOPS) { "circuit already has the maximum number of hops" }
        val index = hops.size + 1
        // HopCipher takes ownership of the copies it is given.
        hops.add(
            Hop(
                HopCipher(keys.forwardKeyCopy(), Direction.FORWARD, index),
                HopCipher(keys.backwardKeyCopy(), Direction.BACKWARD, index),
            ),
        )
        keys.close()
    }

    /** Seals [msg] for hop [targetHop] (default: the last hop). Returns exactly [BODY_SIZE] bytes. */
    @Synchronized
    fun wrapForward(
        msg: RelayMessage,
        targetHop: Int = hops.size,
        random: SecureRandom = SecureRandom(),
    ): ByteArray {
        require(targetHop in 1..hops.size) { "target hop out of range" }
        var cur = RelayMessageCodec.encode(msg, RelayMessageCodec.capacity(targetHop), random)
        for (i in targetHop downTo 1) {
            val plain = typed(if (i == targetHop) TYPE_LOCAL else TYPE_FORWARD, cur)
            cur.fill(0)
            cur = hops[i - 1].forward.seal(plain)
            plain.fill(0)
        }
        check(cur.size == BODY_SIZE) { "layering produced a wrong size" }
        return cur
    }

    /** Peels layers 1..j of a backward cell body until one says ORIGIN; returns (originHop, message).
     * Throws [OnionIntegrityException] on any failure. */
    @Synchronized
    fun unwrapBackward(body: ByteArray): Pair<Int, RelayMessage> {
        if (body.size != BODY_SIZE) throw OnionIntegrityException()
        var cur = body
        for (j in 1..hops.size) {
            val size = layerSize(j)
            if (cur.size < size) throw OnionIntegrityException()
            val opened = hops[j - 1].backward.open(cur.copyOfRange(0, size))
            val type = opened[0]
            val inner = opened.copyOfRange(1, opened.size)
            opened.fill(0)
            when (type) {
                TYPE_ORIGIN ->
                    try {
                        return j to RelayMessageCodec.decode(inner)
                    } catch (e: CellFormatException) {
                        throw OnionIntegrityException()
                    } finally {
                        inner.fill(0)
                    }
                TYPE_WRAPPED -> cur = inner
                else -> {
                    inner.fill(0)
                    throw OnionIntegrityException()
                }
            }
        }
        throw OnionIntegrityException()
    }

    @Synchronized
    override fun close() {
        hops.forEach {
            it.forward.close()
            it.backward.close()
        }
    }

    @Synchronized
    internal fun zeroizedForTest(): Boolean =
        hops.all { h ->
            h.forward.keyRaw.all { it == 0.toByte() } &&
                h.backward.keyRaw.all { it == 0.toByte() }
        }

    override fun toString(): String = "ClientCircuit(hops=$hopCount, REDACTED)"
}

sealed interface ForwardResult {
    /** The cell was addressed to this hop. */
    class Local(
        val message: RelayMessage,
    ) : ForwardResult

    /** The cell must be passed on; [body] is a complete, freshly padded cell body. */
    class Forward(
        val body: ByteArray,
    ) : ForwardResult
}

/** One relay's view of one circuit hop. [hopIndex] is the relay's 1-based position. Not
 * thread-safe: the owning [OnionRelay] serialises calls with a per-circuit lock. */
class RelayHopState internal constructor(
    val hopIndex: Int,
    keys: CircuitHopKeys,
) : AutoCloseable {
    private val forwardCipher = HopCipher(keys.forwardKeyCopy(), Direction.FORWARD, hopIndex)
    private val backwardCipher = HopCipher(keys.backwardKeyCopy(), Direction.BACKWARD, hopIndex)

    init {
        require(hopIndex in 1..MAX_HOPS) { "hop index out of range" }
        keys.close()
    }

    fun unwrapForward(
        body: ByteArray,
        random: SecureRandom = SecureRandom(),
    ): ForwardResult {
        if (body.size != BODY_SIZE) throw OnionIntegrityException()
        val opened = forwardCipher.open(body.copyOfRange(0, layerSize(hopIndex)))
        val type = opened[0]
        val inner = opened.copyOfRange(1, opened.size)
        opened.fill(0)
        try {
            return when (type) {
                TYPE_LOCAL ->
                    try {
                        ForwardResult.Local(RelayMessageCodec.decode(inner))
                    } catch (e: CellFormatException) {
                        throw OnionIntegrityException()
                    }
                TYPE_FORWARD -> ForwardResult.Forward(padToBody(inner, random))
                else -> throw OnionIntegrityException()
            }
        } finally {
            inner.fill(0)
        }
    }

    fun wrapBackward(
        body: ByteArray,
        random: SecureRandom = SecureRandom(),
    ): ByteArray {
        if (body.size != BODY_SIZE) throw OnionIntegrityException()
        val inner = body.copyOfRange(0, BODY_SIZE - hopIndex * LAYER_OVERHEAD)
        val plain = typed(TYPE_WRAPPED, inner)
        inner.fill(0)
        try {
            return padToBody(backwardCipher.seal(plain), random)
        } finally {
            plain.fill(0)
        }
    }

    fun originateBackward(
        msg: RelayMessage,
        random: SecureRandom = SecureRandom(),
    ): ByteArray {
        val m = RelayMessageCodec.encode(msg, RelayMessageCodec.capacity(hopIndex), random)
        val plain = typed(TYPE_ORIGIN, m)
        m.fill(0)
        try {
            return padToBody(backwardCipher.seal(plain), random)
        } finally {
            plain.fill(0)
        }
    }

    override fun close() {
        forwardCipher.close()
        backwardCipher.close()
    }

    internal fun zeroizedForTest(): Boolean =
        forwardCipher.keyRaw.all { it == 0.toByte() } && backwardCipher.keyRaw.all { it == 0.toByte() }

    override fun toString(): String = "RelayHopState(hopIndex=$hopIndex, REDACTED)"
}
